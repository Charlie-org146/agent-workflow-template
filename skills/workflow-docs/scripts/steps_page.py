#!/usr/bin/env python3
"""The Steps page, the per-goal step table, and the preview of step causes (DEL-19).

usage: steps_page.py render [--write] [--root DIR]   the Steps page text, generated from steps.py; --write saves it
       steps_page.py show SLUG [--root DIR]          the final per-step table of one goal (its record)
       steps_page.py file [--root DIR]               each cause the local run records hold, grouped by key, with its fix: previewed
                                                     (filing ships off in v1.1.0; nothing is written to GitHub). Stdlib only."""
import argparse
import importlib
import json
import os
import re
import subprocess
import sys

os.environ.update(GIT_TERMINAL_PROMPT="0", GH_PROMPT_DISABLED="1", GIT_EDITOR="true", GIT_ASKPASS="true", SSH_ASKPASS="true")  # no prompt can hang a script

# One suggested fix per cause (step:CODE). A cause with no entry gets the fix its own code names.
FIX = {"merge:failed": "run goal.py pr SLUG, then merge.py SLUG again",
       "merge:HEAD_MOVED": "run goal.py pr SLUG so the lane runs on the new head, then merge.py SLUG",
       "merge:REQUIREMENT_MISSING": "merge the goal that adds the named requirement text, then merge.py SLUG",
       "merge:PRIVATE_LIST": "create or repair the private-name list (private.py check names the line), then merge.py SLUG",
       "tests:failed": "run the lane again: regression.py run, then goal.py record SLUG tests",
       "tests:LANE_ENV": "free memory or wait, then run the same command again",
       "tests:LANE_DIED": "run the same command again; a second death counts as a try",
       "build:failed": "read the finding, fix its cause, then ask the operation session to resume SLUG",
       "plan:failed": "read the finding, fix the plan, then ask the operation session to resume SLUG",
       "freeze:failed": "give the goal its title, task and at least one done line, then goal.py new again",
       "quick checks:failed": "run the checks named in the finding and fix what they print",
       "after the merge:failed": "run merge.py SLUG again; the release steps resume where they stopped",
       "release:failed": "run merge.py SLUG again, or release.py cut SLUG once the cause is fixed"}


def fix_for(key):
    step, _, code = key.partition(":")
    return FIX.get(key) or "read the refusal that ends with (%s) in the goal's log: goal.py show SLUG; fix its cause, then run the step again" % code
PAGE = os.path.join("docs", "wiki", "Steps.md")


def steps_module():
    sys.dont_write_bytecode = True
    here = os.path.dirname(os.path.abspath(__file__))
    for path in (os.path.join(here, "..", ".."), os.path.join(here, "..", "..", "..", "shared")):
        if os.path.exists(os.path.join(path, "steps.py")):
            sys.path.insert(0, os.path.normpath(path))
            break
    try:
        return importlib.import_module("steps")
    except ImportError:
        sys.exit("REFUSED: steps.py is missing. Fix: reinstall the workflow package (SC_MISSING).")


def render():
    st = steps_module()
    lines = ["# Steps", "", "Generated by steps_page.py from the code; do not edit by hand.", "",
             "Every goal runs these steps in order: " + ", ".join(st.STEPS) + ".", "", "## Older labels", ""]
    lines += ["- %s: %s" % (old, new) for old, new in sorted(st.LEGACY.items())]
    lines += ["", "## What each step records", "",
              "- start, end, active minutes, tokens (per attempt, else 'not reported') and the result, as log lines of the goal's record",
              "- a cause for a step that went wrong: a key `<step>:<CODE>`, previewed once with its fix and grouped with repeats (filing ships off in v1.1.0)", ""]
    return "\n".join(lines)


def stale(root):
    try:
        have = open(os.path.join(root, PAGE)).read()
    except OSError:
        return ["%s is missing. Fix: python3 skills/workflow-docs/scripts/steps_page.py render --write" % PAGE]
    return [] if have == render() else ["%s differs from the code. Fix: python3 skills/workflow-docs/scripts/steps_page.py render --write" % PAGE]


def git(root, *args):
    return subprocess.run(["git", "-C", root] + list(args), capture_output=True, text=True)


def records(root):
    """{slug: record} for every run record of this repository's git common dir; {} where there are none (a CI checkout)."""
    common = git(root, "rev-parse", "--git-common-dir").stdout.strip()
    folder = os.path.join(os.path.abspath(os.path.join(root, common)), "loop", "runs")
    out = {}
    for name in sorted(os.listdir(folder)) if os.path.isdir(folder) else []:
        try:
            out[name[:-5]] = json.load(open(os.path.join(folder, name))) if name.endswith(".json") else None
        except (OSError, ValueError):
            continue
    return {k: v for k, v in out.items() if isinstance(v, dict)}


def cmd_file(args):
    """Filing ships off in v1.1.0: print each cause once, grouped with its repeats, and its fix; write nothing anywhere."""
    st, groups = steps_module(), {}
    for slug, record in records(os.path.abspath(args.root)).items():
        for cause in record.get("causes") or []:
            if isinstance(cause, dict) and st.KEY.match(str(cause.get("key"))):
                groups.setdefault(cause["key"], []).append(slug)
    for key, slugs in sorted(groups.items()):
        print("preview: %s (%d goal%s: %s) -> %s" % (key, len(slugs), "" if len(slugs) == 1 else "s", ", ".join(sorted(slugs)), fix_for(key)))
    if not groups:
        print("preview: no step cause is recorded here")
    return 0


def cmd_show(args):
    st = steps_module()
    record = records(os.path.abspath(args.root)).get(args.slug)
    if record is None:
        sys.exit("REFUSED: no run record for %s here. Fix: run it from the repository the goal belongs to." % args.slug)
    for row in st.entries(record):
        print("%-16s %-8s %4dm  tokens %s  start %s  end %s  %s" % (row["step"], row["state"], row["minutes"], row["tokens"], row["start"] or "-", row["end"] or "-", row["result"]))
    return 0


def cmd_render(args):
    text = render()
    if args.write:
        os.makedirs(os.path.join(args.root, "docs", "wiki"), exist_ok=True)
        open(os.path.join(args.root, PAGE), "w").write(text)
    else:
        print(text)
    return 0


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="cmd", required=True)
    for name, func in (("render", cmd_render), ("show", cmd_show), ("file", cmd_file)):
        item = sub.add_parser(name)
        item.add_argument("--root", default=".")
        item.set_defaults(func=func)
        name == "render" and item.add_argument("--write", action="store_true")
        name == "show" and item.add_argument("slug")
    args = parser.parse_args()
    sys.exit(args.func(args))


if __name__ == "__main__":
    main()
